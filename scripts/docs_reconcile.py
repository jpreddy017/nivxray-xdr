#!/usr/bin/env python3
"""NivXRay XDR · authoritative documentation reconciliation.

Owner directive (2026-06): documentation must not be able to lie, and the
TARGET SPECIFICATION must be allowed to run ahead of the code.

THREE TRUTH LAYERS — never mixed:
  1. CURRENT_REALITY       generated from runtime/repository truth
  2. TARGET_SPEC           what NivXRay is designed to become
  3. HISTORICAL_RECORD     previous plans/decisions, kept for provenance

Every authoritative document declares its layer in a front-matter block:

    <!-- NIVX-DOC
    layer: CURRENT_REALITY | TARGET_SPEC | HISTORICAL_RECORD
    status: GENERATED | ADOPTED | AUTHORED | SPEC_PENDING
    generated_by: scripts/docs_reconcile.py   (GENERATED only)
    -->

THE GATE fails only when a document asserts something as CURRENT REALITY
that runtime/repository evidence contradicts.  A TARGET_SPEC document may
describe a Windows sensor that does not exist — it just has to say
TARGET / SPEC_PENDING / NOT_IMPLEMENTED rather than claiming it works.

    python3 scripts/docs_reconcile.py            # generate + gate
    python3 scripts/docs_reconcile.py --gate     # gate only (CI)
"""
from __future__ import annotations

import ast
import collections
import json
import os
import pathlib
import re
import sys
from datetime import datetime, timezone

ROOT = pathlib.Path("/app")
BACKEND = ROOT / "backend"
DOCS = ROOT / "docs" / "nivxray-xdr"
MEMORY = ROOT / "memory"
FE = ROOT / "apps" / "nivxray-xdr" / "src"

STAMP = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%MZ")

FM = """<!-- NIVX-DOC
layer: {layer}
status: {status}
generated_by: scripts/docs_reconcile.py
generated_at: {stamp}
-->

> **DO NOT EDIT BY HAND.** Regenerated by `scripts/docs_reconcile.py`.
> This file is **CURRENT REALITY** extracted from the running system.
> Target-state intent belongs in `02_ARCHITECTURE/` and `03_DESIGN/`.

"""


# ══════════════════════════════════════════════════════════════════
# 1 · RUNTIME / REPOSITORY TRUTH EXTRACTION
# ══════════════════════════════════════════════════════════════════
def truth() -> dict:
    """Everything the documentation is allowed to assert as reality."""
    t: dict = {"stamp": STAMP}
    sys.path.insert(0, str(BACKEND))
    os.chdir(BACKEND)
    try:
        from dotenv import load_dotenv
        load_dotenv(BACKEND / ".env")
    except Exception:
        pass

    # ── backend routes (imports the real app) ──────────────────────
    routes = []
    try:
        import server
        for r in server.app.routes:
            p = getattr(r, "path", "")
            if p.startswith("/api"):
                routes.append({"path": p,
                               "methods": sorted(getattr(r, "methods", []) or []),
                               "name": getattr(r, "name", "")})
    except Exception as e:                                  # pragma: no cover
        t["route_error"] = str(e)
    t["routes"] = sorted(routes, key=lambda r: r["path"])

    # ── capability registry ────────────────────────────────────────
    caps = []
    try:
        from edr_plane.capability import inventory as inv
        for c in inv.INVENTORY:
            caps.append({
                "id": c.capability_id, "name": c.name,
                "plane": str(c.plane).split(".")[-1],
                "domain": c.domain,
                "declared": str(c.declared_state).split(".")[-1],
                "effective": str(c.effective_state).split(".")[-1],
                "operational": bool(c.is_operational),
                "gap": str(c.gap_class).split(".")[-1] if c.gap_class else "NONE",
                "telemetry": str(c.telemetry_status).split(".")[-1]
                             if c.telemetry_status else "",
                "evidence": c.evidence_reference or "",
            })
    except Exception as e:                                  # pragma: no cover
        t["cap_error"] = str(e)
    t["capabilities"] = caps

    # ── declared engines ───────────────────────────────────────────
    eng = set()
    for p in BACKEND.rglob("*.py"):
        if "__pycache__" in str(p):
            continue
        try:
            eng |= set(re.findall(r'"(nivxray::[a-z0-9_:{}.]+)"', p.read_text()))
        except Exception:
            pass
    t["engines"] = sorted(e for e in eng
                          if "{" not in e and "nonexistent" not in e)

    # ── endpoint-keyed store contract (P0-2C) ──────────────────────
    try:
        from services.edr.endpoint_query import ENDPOINT_KEYED_STORES
        t["endpoint_keyed_stores"] = {k: list(v)
                                      for k, v in ENDPOINT_KEYED_STORES.items()}
    except Exception:
        t["endpoint_keyed_stores"] = {}

    # ── sensors that actually exist (producers, not contracts) ─────
    agents = ROOT / "agents"
    t["sensors"] = sorted(p.name for p in agents.iterdir()
                          if p.is_dir()) if agents.exists() else []

    # ── frontend routes ────────────────────────────────────────────
    fe = []
    app = FE / "App.jsx"
    if app.exists():
        src = app.read_text()
        for m in re.finditer(r'path="([^"]+)"[^>]*element=\{<[^>]*?'
                             r'(?:<)?([A-Za-z0-9_]+)\s*/?>', src):
            fe.append({"route": m.group(1), "component": m.group(2)})
        if not fe:
            fe = [{"route": r, "component": ""}
                  for r in re.findall(r'path="([^"]+)"', src)]
    t["ui_routes"] = fe

    # ── proof scripts + their declared gate names ──────────────────
    proofs = []
    for p in sorted((ROOT / "scripts").glob("*.py")):
        head = ""
        try:
            head = p.read_text()[:900]
        except Exception:
            pass
        proofs.append({"script": f"scripts/{p.name}",
                       "is_proof": "proof" in p.name,
                       "title": (head.split("\n")[1][:110]
                                 if head.startswith('"""') and "\n" in head
                                 else "")})
    t["proofs"] = proofs

    # ── test inventory ─────────────────────────────────────────────
    t["test_files"] = sorted(str(p.relative_to(BACKEND))
                             for p in (BACKEND / "tests").rglob("test_*.py"))

    # ── real telemetry facts (the honesty anchor) ──────────────────
    try:
        from pymongo import MongoClient
        db = MongoClient(os.environ["MONGO_URL"])[os.environ["DB_NAME"]]
        real = {"sensor_version": "0.1.0"}
        latest = list(db["edr_raw_events"].find(
            real, {"_id": 0, "ingest_time": 1}).sort("ingest_time", -1).limit(1))
        t["telemetry"] = {
            "real_sensor_events": db["edr_raw_events"].count_documents(real),
            "non_sensor_events": db["edr_raw_events"].count_documents(
                {"sensor_version": {"$ne": "0.1.0"}}),
            "last_real_delivery": (latest[0]["ingest_time"] if latest
                                   else None),
            "real_reporting_endpoints": len(
                db["edr_raw_events"].distinct("endpoint_ref", real)),
            "enrolments": db["edr_endpoints"].count_documents({}),
            "platforms": sorted(str(p) for p in
                                db["edr_endpoints"].distinct("platform") if p),
            "incidents": db["workspace_cases"].count_documents({}),
            "incidents_with_provenance": db["workspace_cases"].count_documents(
                {"provenance": {"$exists": True}}),
            "canonical_events": db["xdr_canonical_events"].count_documents({}),
            "detections_from_real": db["edr_raw_events"].count_documents(
                {**real, "derivations.outcome": "DETECTION_MATCHED"}),
            "response_commands": db["edr_response_commands"].count_documents({}),
            "response_by_state": dict(collections.Counter(
                d.get("state") for d in
                db["edr_response_commands"].find({}, {"state": 1}))),
        }
    except Exception as e:
        t["telemetry"] = {"error": str(e)}
    return t


# ══════════════════════════════════════════════════════════════════
# 2 · GENERATED DOCUMENTS (CURRENT_REALITY layer)
# ══════════════════════════════════════════════════════════════════
def write(rel: str, body: str, layer="CURRENT_REALITY", status="GENERATED"):
    p = DOCS / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(FM.format(layer=layer, status=status, stamp=STAMP) + body)
    return rel


def gen_route_inventory(t) -> str:
    rs = t["routes"]
    by = collections.Counter("/".join(r["path"].split("/")[:4]) for r in rs)
    lines = [f"# Backend Route Inventory — CURRENT REALITY\n",
             f"**{len(rs)} live `/api` routes** extracted from the running "
             f"FastAPI app at `{t['stamp']}`.\n",
             "> A route is **not** a component. This inventory exists to "
             "expose surface area, duplication and dead ends — see "
             "`02_ARCHITECTURE/COMPONENT_ARCHITECTURE.md` for the "
             "component model that governs them.\n",
             "## Surface area by prefix\n",
             "| Routes | Prefix |", "|---:|---|"]
    lines += [f"| {v} | `{k}` |" for k, v in by.most_common()]
    lines += ["\n## Full inventory\n", "| Method(s) | Path | Handler |",
              "|---|---|---|"]
    lines += [f"| {','.join(r['methods']) or '—'} | `{r['path']}` | "
              f"`{r['name']}` |" for r in rs]
    return "\n".join(lines) + "\n"


def gen_capability_matrix(t) -> str:
    caps = t["capabilities"]
    eff = collections.Counter(c["effective"] for c in caps)
    gap = collections.Counter(c["gap"] for c in caps)
    dom = collections.Counter(c["domain"] for c in caps)
    op = sum(1 for c in caps if c["operational"])
    L = [f"# Capability Matrix — CURRENT REALITY\n",
         f"**{len(caps)} catalogued capabilities**, read from "
         f"`backend/edr_plane/capability/inventory.py` at `{t['stamp']}`.\n",
         "> **This is a registry fact, not a completion score.** "
         "`is_operational` counts capabilities whose telemetry, backend, "
         "control driver and UI are ALL live. It is not a percentage of "
         "product readiness and must never be quoted as one.\n",
         f"- `is_operational = true` · **{op} of {len(caps)}**",
         "\n## By effective state\n", "| State | Count |", "|---|---:|"]
    L += [f"| `{k}` | {v} |" for k, v in eff.most_common()]
    L += ["\n## By gap class (what is actually missing)\n",
          "| Gap | Count | Meaning |", "|---|---:|---|"]
    MEAN = {"TELEMETRY_MISSING": "no producer emits this evidence yet",
            "CONTROL_DRIVER_MISSING": "no control plane can execute it",
            "UI_ONLY": "a surface exists with no authoritative backend",
            "BACKEND_ONLY": "backend exists with no analyst surface",
            "OWNER_INPUT_PENDING": "blocked on an owner decision",
            "NONE": "no gap recorded"}
    L += [f"| `{k}` | {v} | {MEAN.get(k, '—')} |" for k, v in gap.most_common()]
    L += ["\n## By domain\n", "| Domain | Capabilities | Operational |",
          "|---|---:|---:|"]
    for d, n in dom.most_common():
        L.append(f"| {d} | {n} | "
                 f"{sum(1 for c in caps if c['domain'] == d and c['operational'])} |")
    L += ["\n## Full matrix\n",
          "| Capability | Plane | Domain | Effective state | Operational | "
          "Gap | Evidence |", "|---|---|---|---|:-:|---|---|"]
    for c in caps:
        L.append(f"| `{c['id']}` | {c['plane']} | {c['domain']} | "
                 f"`{c['effective']}` | {'✔' if c['operational'] else '—'} | "
                 f"`{c['gap']}` | {c['evidence'][:60] or '—'} |")
    return "\n".join(L) + "\n"


def gen_engine_registry(t) -> str:
    L = [f"# Engine / Service Registry — CURRENT REALITY\n",
         f"**{len(t['engines'])} declared engine identities** found in the "
         f"repository at `{t['stamp']}`.\n",
         "> An engine package is **not** automatically a product "
         "capability. Each engine below must appear in "
         "`COMPONENT_ARCHITECTURE.md` with an owner, an SSOT and a UI "
         "consumer, or be classified `ORPHAN` / `LEGACY_UNWIRED`.\n",
         "| Engine identity |", "|---|"]
    L += [f"| `{e}` |" for e in t["engines"]]
    L += ["\n## Endpoint-keyed evidence stores (P0-2C contract)\n",
          "Declared in `backend/services/edr/endpoint_query.py`. A query "
          "against any of these using a raw caller-supplied identifier is a "
          "guarded invariant violation.\n",
          "| Store | Declared identity fields |", "|---|---|"]
    for s, f in sorted(t["endpoint_keyed_stores"].items()):
        L.append(f"| `{s}` | {', '.join(f'`{x}`' for x in f)} |")
    return "\n".join(L) + "\n"


def gen_ui_route_inventory(t) -> str:
    rs = t["ui_routes"]
    xdr = [r for r in rs if r["route"].startswith("/xdr")]
    edr = [r for r in rs if r["route"].startswith("/edr")]
    oth = [r for r in rs if r not in xdr and r not in edr]
    L = [f"# Frontend Route Inventory — CURRENT REALITY\n",
         f"**{len(rs)} routes** from `apps/nivxray-xdr/src/App.jsx` at "
         f"`{t['stamp']}` — NivXRay XDR **{len(xdr)}** · NivXForge EDR "
         f"**{len(edr)}** · shared **{len(oth)}**.\n",
         "> A UI page is **not** proof of an operational component. Every "
         "route must map to a screen spec in `03_DESIGN/` and to "
         "authoritative APIs.\n"]
    for label, group in (("NivXRay XDR", xdr), ("NivXForge EDR", edr),
                         ("Shared / shell", oth)):
        L += [f"\n## {label}\n", "| Route | Component |", "|---|---|"]
        L += [f"| `{r['route']}` | `{r['component'] or '—'}` |" for r in group]
    return "\n".join(L) + "\n"


