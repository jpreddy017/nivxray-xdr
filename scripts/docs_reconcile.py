         f"{sum(1 for c in caps if c['operational'])}** |",
         f"| Runtime proof scripts | "
         f"**{sum(1 for p in t['proofs'] if p['is_proof'])}** |",
         f"| Test modules | **{len(t['test_files'])}** |",
