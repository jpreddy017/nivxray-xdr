# 3 · THE GATE
# ══════════════════════════════════════════════════════════════════
CLAIM_RULES = [
    # (regex claim, predicate(truth) -> ok, failure explanation)
    (r"windows\s+sensor\s+(?:is\s+)?(?:operational|live|shipping|"
     r"real_runtime_verified|end_to_end_validated)",
     lambda t: any("windows" in s.lower() for s in t["sensors"]),
     "no Windows producer exists under /app/agents"),
    (r"macos\s+sensor\s+(?:is\s+)?(?:operational|live|shipping)",
     lambda t: any("macos" in s.lower() for s in t["sensors"]),
     "no macOS producer exists under /app/agents"),
    (r"isolation\s+(?:is\s+)?(?:operational|verified|working|enforced)",
     lambda t: False,
     "endpoint isolation is BLOCKED_ENVIRONMENT (no CAP_NET_ADMIN) and has "
     "never been verified"),
    (r"(?:second|independent)\s+telemetry\s+domain\s+(?:is\s+)?"
     r"(?:operational|live|integrated)",
     lambda t: len([p for p in t["telemetry"].get("platforms", [])]) > 1
     and False,
     "only the endpoint telemetry domain has a real producer"),
    (r"(?:we are|nivxray is|product is)\s+(?:ga|generally available|"
     r"production[- ]ready)",
     lambda t: False,
     "no GA gate has been passed; see 09_RELEASE/GA_PLAN.md"),
]

LAYER_RE = re.compile(r"^layer:\s*(\S+)", re.M)
STATUS_RE = re.compile(r"^status:\s*(\S+)", re.M)
HEDGE = ("TARGET", "SPEC_PENDING", "NOT_IMPLEMENTED", "REQUIRED",
         "PLANNED", "BLOCKED", "MUST ", "SHOULD ", "WILL ", "GOAL",
         "REFERENCE_CAPTURE_REQUIRED", "CONTRACT_DEFINED")


def numeric_drift(t) -> list:
    """Hand-written inventory counts must match the runtime.

    This rule exists because it caught a real drift on its first day:
    authored documents quoted 61 engines and 60 UI routes while the
    generator read 64 and 58. Prose that quotes a generated number is
    prose that will silently go stale — exactly how
    `memory/CAPABILITY_REGISTRY.md` came to disagree with the code.
    """
    live = {
        "route": (len(t["routes"]),
                  re.compile(r"\*\*(\d{2,5})\*\* live `/api` routes|"
                             r"\*\*(\d{2,5})\*\* live API routes|"
                             r"(\d{2,5}) live API routes")),
        "engine": (len(t["engines"]),
                   re.compile(r"(\d{1,4}) (?:declared )?engines?\b|"
                              r"(\d{1,4}) declared engine identit")),
        "ui route": (len(t["ui_routes"]),
                     re.compile(r"(\d{1,4}) UI routes?\b")),
        "capability": (len(t["capabilities"]),
                       re.compile(r"(\d{1,4}) catalogued capabilit")),
    }
    out = []
    for p in sorted(DOCS.rglob("*.md")):
        txt = p.read_text()
        if STATUS_RE.search(txt) and \
                STATUS_RE.search(txt).group(1) == "GENERATED":
            continue                       # generated docs ARE the truth
        for i, line in enumerate(txt.splitlines(), 1):
            for label, (real, rx) in live.items():
                for m in rx.finditer(line):
                    got = next((g for g in m.groups() if g), None)
                    if got and int(got) != real:
                        out.append((str(p.relative_to(ROOT)), i,
                                    f"hand-written {label} count {got} "
                                    f"disagrees with runtime ({real}) — "
                                    f"cite 08_VALIDATION/REALITY_MATRIX.md "
                                    f"instead of restating it"))
    return out


def gate(t) -> list:
    """Fail only where a doc asserts CURRENT REALITY that runtime
    evidence contradicts.  TARGET_SPEC is explicitly permitted to be
    ahead of the code."""
    fails = []
    if not DOCS.exists():
        return [("<tree>", 0, "documentation tree does not exist")]
    for p in sorted(DOCS.rglob("*.md")):
        rel = str(p.relative_to(ROOT))
        txt = p.read_text()
        m = LAYER_RE.search(txt)
        st = STATUS_RE.search(txt)
        if not m:
            fails.append((rel, 0, "missing NIVX-DOC front matter: every "
                                  "authoritative doc must declare its "
                                  "truth layer"))
            continue
        layer = m.group(1)
        if layer not in ("CURRENT_REALITY", "TARGET_SPEC",
                         "HISTORICAL_RECORD"):
            fails.append((rel, 0, f"unknown truth layer `{layer}`"))
        if st and st.group(1) not in ("GENERATED", "ADOPTED", "AUTHORED",
                                      "SPEC_PENDING"):
            fails.append((rel, 0, f"unknown status `{st.group(1)}`"))
        if layer != "CURRENT_REALITY":
            continue                      # target/history may run ahead
        for i, line in enumerate(txt.splitlines(), 1):
            low = line.lower()
            if any(h.lower() in low for h in HEDGE):
                continue                  # explicitly hedged, not a claim
            for rx, ok, why in CLAIM_RULES:
                if re.search(rx, low) and not ok(t):
                    fails.append((rel, i, f"CURRENT_REALITY claim "
                                          f"contradicted by runtime: {why}"))
    # SPEC_PENDING completeness
    REQ = ("Purpose", "Owner", "Dependencies", "Required source inputs",
           "Known current reality", "Unresolved questions",
           "Completion criteria", "Release stage")
    for p in sorted(DOCS.rglob("*.md")):
        txt = p.read_text()
        st = STATUS_RE.search(txt)
        if st and st.group(1) == "SPEC_PENDING":
            missing = [r for r in REQ if r.lower() not in txt.lower()]
            if missing:
                fails.append((str(p.relative_to(ROOT)), 0,
                              f"SPEC_PENDING doc missing required sections: "
                              f"{', '.join(missing)} (no generic filler "
                              f"allowed)"))
    fails += numeric_drift(t)
    return fails


