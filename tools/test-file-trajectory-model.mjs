import assert from 'node:assert/strict';
import { clusterEvents, chronological, eventKey, eventStyle, positionEvents, readComputerPage } from '../apps/nivxray-xdr/src/nivxforge/files/trajectoryModel.mjs';
const a = { record_id: 'same', endpoint_id: 'a', observed_at: '2026-11-01T01:00:00Z' };
const b = { ...a, endpoint_id: 'b' };
assert.notEqual(eventKey(a), eventKey(b), 'endpoint identity must be part of event key');
const start = Date.parse('2026-11-01T00:00:00Z'), end = start + 86400000;
assert.equal(chronological([{ ...a, record_id: 'later', observed_at: '2026-11-01T03:00:00Z' }, a])[0], a);
const positions = positionEvents(Array.from({ length: 20 }, (_, n) => ({ ...a, record_id: String(n) })), start, end);
assert.equal(new Set(positions.map((p) => p.lane)).size, 20, 'same-time markers never overlap');
assert.equal(positionEvents([a], start, start + 1000).length, 0, 'zoom excludes outside events');
assert.equal(eventStyle('file_created').icon, 'file');
assert.equal(eventStyle('unknown').label, 'Other observation');
const groups = clusterEvents([a, b], start, end);
assert.equal(groups.length, 1);
assert.equal(groups[0].rows.length, 2, 'clusters retain every event for drill-down');
const calls = [];
const query = { endpoint_ids: ['a','b','c','d','e'], key_type: 'sha256', key: 'a'.repeat(64), time_start: start, time_end: end, limit: 100 };
const read = async (q) => { calls.push(q); return { observations: [{ ...a, endpoint_id: 'untrusted-source-alias' }], next_cursor: q.endpoint_id === 'a' && !q.cursor ? 'a-next' : null }; };
const signal = new AbortController().signal;
const first = await readComputerPage(read, query, signal);
assert.equal(calls.length, 4, 'one interaction issues no more than four scans');
assert.equal(first.observations[0].endpoint_id, 'a', 'requested authorized endpoint owns the view');
assert.equal(first.complete, false);
const second = await readComputerPage(read, query, signal, first.next_cursor);
assert.equal(second.complete, true);
assert.deepEqual(calls.map((c) => c.endpoint_id), ['a','b','c','d','e','a']);
assert.equal(calls[5].cursor, 'a-next');
assert(!('endpoint_ids' in calls[0]), 'fleet-only query is never passed to endpoint API');
await assert.rejects(readComputerPage(async () => ({ state: 'ENDPOINT_NOT_RESOLVED' }), query, signal));
const abort = new AbortController(); abort.abort();
await assert.rejects(readComputerPage(read, query, abort.signal), { name: 'AbortError' });
const direct = await readComputerPage(async (q) => q, { endpoint_id: 'a' }, signal, 'direct-cursor');
assert.equal(direct.cursor, 'direct-cursor');
console.log('File trajectory model: chronology, collision layout, zoom, identity, bounded scans, continuation, unresolved endpoints and cancellation passed.');
